// DYX Autonomous / Phase 2H4J -- offline, transport-neutral request lifecycle.
// Not a TCP listener, TLS/authentication provider, asynchronous queue, or
// permission to dispatch mission/PX4/actuator commands. All clock samples and
// request IDs MUST originate at trusted ingress, never from Android payloads.
// Single-owner executor only; synchronize externally before sharing instances.

#include "dyx_rpp_cpp17_core/backend_http_wire.hpp"
